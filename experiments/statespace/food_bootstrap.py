"""Paired food x recorded-template (pigeonhole) bootstrap for separation scores.

Resample food names and template families independently, with replacement. An
anchor's replicate weight is the product of its food and template multiplicities.
Use the same weights for every model and normalize by total anchor weight.
Original examples without recorded template IDs get singleton template clusters;
this cannot account for unknown shared generation patterns in those examples.
"""
from hashlib import sha256
from itertools import combinations

import numpy as np


def template_cluster(key, item):
    """Group alternate surface forms generated by the same explicit rule."""
    if 'template' not in item:
        return 'unrecorded:' + key
    from generate_food_additions import RULES
    matches = [rx.pattern for rx, *_ in RULES if rx.fullmatch(item['template'])]
    if len(matches) != 1:
        raise ValueError(f'Expected one generating rule for {key}: {matches}')
    return 'rule:' + sha256(matches[0].encode()).hexdigest()[:16]


def two_way_bootstrap(values, foods, templates, n_boot=2000, seed=0):
    """values [anchor, model, metric] -> bootstrap means [replicate, model, metric]."""
    values = np.asarray(values, dtype=np.float64)
    if values.ndim != 3 or not len(values):
        raise ValueError('Expected a nonempty [anchor, model, metric] array')
    if len(values) != len(foods) or len(values) != len(templates):
        raise ValueError('Every anchor needs a food and template cluster')
    fs, fi = np.unique(foods, return_inverse=True)
    ts, ti = np.unique(templates, return_inverse=True)
    rng = np.random.default_rng(seed)
    draws = []
    empty = 0
    while len(draws) < n_boot:
        fw = np.bincount(rng.integers(len(fs), size=len(fs)), minlength=len(fs))
        tw = np.bincount(rng.integers(len(ts), size=len(ts)), minlength=len(ts))
        weights = fw[fi] * tw[ti]
        total = weights.sum()
        if not total:
            empty += 1
            if empty > 100 * n_boot:
                raise RuntimeError('Too many empty food-template intersections')
            continue
        draws.append(np.einsum('i,ijk->jk', weights, values) / total)
    return np.stack(draws), empty


def comparisons(means, draws, models, metric=0):
    """Paired percentile intervals for every model difference."""
    out = {}
    for a, b in combinations(range(len(models)), 2):
        lo, hi = np.quantile(draws[:, a, metric] - draws[:, b, metric], [.025, .975])
        out[f'{models[a]} minus {models[b]}'] = {
            'difference': float(means[a, metric] - means[b, metric]),
            'ci95': [float(lo), float(hi)],
        }
    return out
